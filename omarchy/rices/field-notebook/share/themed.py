# ------------------------------------------------------------ Firefox
def firefox_profiles():
    for base in (HOME / ".config/mozilla/firefox", HOME / ".mozilla/firefox"):
        ini = base / "profiles.ini"
        if not ini.exists():
            continue
        cp = configparser.ConfigParser()
        cp.read(ini)
        for sec in cp.sections():
            if not sec.startswith("Profile") or "Path" not in cp[sec]:
                continue
            p = cp[sec]["Path"]
            path = base / p if cp[sec].get("IsRelative", "1") == "1" else pathlib.Path(p)
            if path.is_dir():
                yield path


