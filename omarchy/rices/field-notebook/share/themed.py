def main():
    if not COLORS.exists():
        print(f"no active theme colors at {COLORS}", file=sys.stderr)
        return 1
    c = load_colors()
    for step in (cava, spotify, firefox, gh_dash):
        try:
            step(c)
        except Exception as e:  # one app failing must not stop the others
            print(f"themed.py: {step.__name__}: {e}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
