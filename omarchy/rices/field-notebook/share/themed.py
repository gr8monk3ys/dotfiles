#!/usr/bin/env python3
"""Regenerate app styles from the active Omarchy theme.

Omarchy already themes terminals, btop, Chromium/Brave, Neovim and Claude Code
from colors.toml. This covers the rest of the Field Notebook setup: cava,
spotify_player and Firefox. Runs from the theme-set hook, so any theme you
switch to carries through; safe to run by hand.
"""
import configparser
import pathlib
import re
import subprocess
import sys
import tomllib

HOME = pathlib.Path.home()
COLORS = HOME / ".local/state/omarchy/current/theme/colors.toml"
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def load_colors():
    with open(COLORS, "rb") as f:
        raw = tomllib.load(f)
    c = {k: v for k, v in raw.items() if isinstance(v, str) and HEX.match(v)}
    # Fall back sensibly for themes that leave optional keys out.
    c.setdefault("accent", c.get("blue", "#7aa2f7"))
    c.setdefault("lighter_background", c["background"])
    c.setdefault("dark_background", c["background"])
    c.setdefault("darker_background", c["dark_background"])
    c.setdefault("dark_foreground", c.get("muted", c["foreground"]))
    c.setdefault("bright_foreground", c["foreground"])
    c.setdefault("muted", c["dark_foreground"])
    c.setdefault("selection", c["lighter_background"])
    c["mode"] = raw.get("mode", "dark")
    return c


def mix(a, b, t):
    """Blend hex a toward hex b by t (0..1)."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb))


MARK = "themed.py"   # every generated file names its generator in its header


def write(path, text):
    path = pathlib.Path(path)
    # A symlink is someone else's managed file (the dotfiles stow cava's
    # config): leave it alone rather than replace the link with a copy.
    if path.is_symlink():
        print(f"themed.py: {path} is a symlink; not overwriting it", file=sys.stderr)
        return
    # A hand-written file is kept once, as <file>.dotfiles-bak, before the
    # first overwrite; later runs only replace what this script generated.
    if path.exists() and MARK not in path.read_text(errors="ignore")[:400]:
        backup = path.with_name(path.name + ".dotfiles-bak")
        if not backup.exists():
            path.replace(backup)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


# ---------------------------------------------------------------- cava
def cava(c):
    grad = [mix(c["background"], c["accent"], 0.45), c["accent"],
            mix(c["accent"], c["bright_foreground"], 0.35), mix(c["accent"], c["bright_foreground"], 0.7)]
    lines = "\n".join(f"gradient_color_{i + 1} = '{g}'" for i, g in enumerate(grad))
    write(HOME / ".config/cava/config", f"""\
# Generated by ~/.local/share/field-notebook/themed.py from the Omarchy theme.
# Edit that script (or the [general]/[smoothing] values there), not this file.
[general]
framerate = 60
autosens = 1
bar_width = 2
bar_spacing = 1
lower_cutoff_freq = 40
higher_cutoff_freq = 12000

[input]
method = pipewire
source = auto

[output]
method = noncurses
channels = stereo
mono_option = average
reverse = 0

[color]
background = default
foreground = '{c["accent"]}'
gradient = 1
gradient_count = {len(grad)}
{lines}

[smoothing]
monstercat = 1
waves = 0
noise_reduction = 77
""")
    # SIGUSR1 makes a running cava reload its config.
    subprocess.run(["pkill", "-USR1", "-x", "cava"], check=False)


